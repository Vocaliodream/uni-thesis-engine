#!/usr/bin/env bash
# Register the uni-thesis-engine pre-commit gate in .git/hooks/pre-commit.
#   Gate 1: pytest (warnings are errors, coverage floor 90 %)
#   Gate 2: scripts/audit_anti_hallucination.py (hermetic: every profile is regenerated
#           offline with the current code + templates, then audited)
# Any failing gate exits non-zero and blocks the commit.  Bypass only with `git commit --no-verify`.
set -euo pipefail

ROOT="$(git -C "$(dirname "${BASH_SOURCE[0]}")" rev-parse --show-toplevel)"
HOOK_DIR="$(git -C "$ROOT" rev-parse --git-path hooks)"
case "$HOOK_DIR" in /*) ;; *) HOOK_DIR="$ROOT/$HOOK_DIR" ;; esac
mkdir -p "$HOOK_DIR"
HOOK="$HOOK_DIR/pre-commit"
PY="${PYTHON:-$(command -v python3 || command -v python)}"

if [ -e "$HOOK" ] && ! grep -q "uni-thesis-engine pre-commit gate" "$HOOK"; then
  cp "$HOOK" "$HOOK.bak"
  echo "existing pre-commit hook saved to $HOOK.bak"
fi

cat > "$HOOK" <<HOOK_EOF
#!/usr/bin/env bash
# uni-thesis-engine pre-commit gate (generated by scripts/install_hooks.sh)
set -uo pipefail
cd "\$(git rev-parse --show-toplevel)"
PY="\${PYTHON:-$PY}"

echo "[pre-commit] gate 1/2: pytest + coverage"
if ! "\$PY" -m pytest -q -W error --cov=src/uni_thesis --cov-report=term --cov-fail-under=90; then
  echo "[pre-commit] BLOCKED: tests or coverage floor failed" >&2
  exit 1
fi

echo "[pre-commit] gate 2/2: anti-hallucination audit"
if ! "\$PY" scripts/audit_anti_hallucination.py; then
  echo "[pre-commit] BLOCKED: anti-hallucination audit failed" >&2
  exit 1
fi
echo "[pre-commit] all gates passed"
HOOK_EOF
chmod +x "$HOOK"
echo "installed $HOOK (python: $PY)"
